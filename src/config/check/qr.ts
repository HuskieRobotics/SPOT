/**
 * CC-7 (revised by #358): the QR layout is derived from match-scouting.json, so there is nothing
 * to size. What can still go wrong is that the scouting screen records something a QR code cannot
 * carry, or so much that a long match no longer fits one code. Generated matches go through the
 * encoder and decoder to find out.
 */
import type { MatchScoutingConfig } from "../types";
import type { Action, TeamMatchPerformance } from "@/data/types";
import { generate } from "@/generate/synthetic";
import { actionsPerCode, decodePerformance, encodePerformance, QrError } from "@/qr/codec";
import { qrLayout } from "@/qr/layout";
import type { Reporter } from "./report";

/** Below this many positioned actions in one code, a long match may not fit (the most in real 2026 data: 68). */
export const QR_ACTIONS_WANTED = 200;

const MS = "match-scouting" as const;

function sameAction(a: Action, b: Action): boolean {
  const pos = (x: Action) => JSON.stringify(x.other?.pos ?? null);
  return (
    a.id === b.id &&
    a.ts === b.ts &&
    a.phase === b.phase &&
    a.segment === b.segment &&
    a.segmentKind === b.segmentKind &&
    a.segmentIndex === b.segmentIndex &&
    pos(a) === pos(b)
  );
}

/**
 * Report the first generated match that does not survive a QR code. `performances` defaults to
 * 20 matches generated by the configuration's rules.
 */
export function checkQr(
  ms: MatchScoutingConfig,
  report: Reporter,
  performances: TeamMatchPerformance[] = generate({
    config: ms,
    seed: "config:check qr",
    matches: 20,
  }).performances,
): void {
  const layout = qrLayout(ms);
  for (const p of performances) {
    let message: string | null = null;
    try {
      const back = decodePerformance(encodePerformance(p, layout), layout);
      const n = p.actions.findIndex((a, i) => !back.actions[i] || !sameAction(a, back.actions[i]));
      if (n >= 0 || back.actions.length !== p.actions.length)
        message = `action ${n + 1} (${p.actions[n]?.id}) came back changed`;
    } catch (error) {
      if (!(error instanceof QrError)) throw error;
      message = error.message;
    }
    if (message) {
      report.error(
        MS,
        [],
        `A match scouted with this configuration cannot be sent by QR code: ${message}`,
        "Scouters without a connection could not hand in such a match. If the configuration looks right, this is a bug in SPOT; please report it.",
      );
      return;
    }
  }
  const fits = actionsPerCode(layout, true);
  if (fits < QR_ACTIONS_WANTED)
    report.warning(
      MS,
      [],
      `One QR code holds ${fits} actions with positions (${layout.buttons.length} buttons, ${layout.placements.length} periods), so a long match may not fit one code and must be synced instead of scanned.`,
      "Fewer buttons or fewer periods leave room for more actions.",
    );
}
